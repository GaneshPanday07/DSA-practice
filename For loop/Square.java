//Find the square of every number from 1 to 20
public class Square {
    public static void main(String[] args){
        
        //Find the square of every number from 1 to 20
        for(int i = 1; i<=20; i++){
            System.out.println(i*i);
        }


        //Print cubes from 1 to 15
        for (int i = 1; i <= 15; i++) {
            System.out.println(i * i * i);
        }
    }
}
